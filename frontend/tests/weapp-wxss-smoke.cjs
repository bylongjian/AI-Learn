const assert = require('node:assert/strict')
const { spawnSync } = require('node:child_process')
const path = require('node:path')
const fs = require('node:fs')
const compiler = process.argv[2]
assert.ok(compiler, 'Pass the installed official WeChat wcsc.exe path')
const root = path.resolve(__dirname,'../dist/weapp')
const files = fs.readdirSync(root,{recursive:true}).filter(file => file.endsWith('.wxss')).map(file => file.replaceAll('\\','/'))
assert.ok(files.includes('app.wxss'), 'Build the app before compiling its emitted styles')
const run = spawnSync(compiler, ['-pc', String(files.length), ...files], { cwd:root, encoding:'utf8', windowsHide:true, maxBuffer:8*1024*1024 })
assert.equal(run.status, 0, run.stderr || run.error?.message || 'WeChat WXSS compilation failed')
console.log(`WeChat native WXSS compilation passed (${files.length} emitted stylesheets).`)
